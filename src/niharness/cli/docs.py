"""`nih docs generate`: regenerate everything that is derived.

JSON Schemas are the contract with the TUI, and three documentation pages are
rendered from code. They are committed, and the gate fails when they are stale,
so nobody hand-edits a generated page.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any

import typer
from pydantic import BaseModel
from typer.testing import CliRunner

from niharness.config import HarnessConfig, ModelsConfig, SandboxConfig, VectorConfig
from niharness.domain.artifacts import ARTIFACT_MODELS
from niharness.domain.context import CompactionPolicy
from niharness.domain.control import ControlMessage
from niharness.domain.events import PAYLOAD_TYPES, Event
from niharness.domain.gate import GATE_MATRIX, GateTier
from niharness.domain.loop import LoopThresholds
from niharness.domain.state import RunSnapshot
from niharness.domain.tools import TOOL_ARGUMENTS, ToolCall, ToolLimits

# REUSE-IgnoreStart - the lines below are the generated pages' header, not this file's
GENERATED_WARNING = "\n".join(
    [
        "<!--",
        "SPDX-FileCopyrightText: 2026 Mateusz Okulanis",
        "SPDX-License-Identifier: GPL-3.0-or-later",
        "",
        "Generated by `nih docs generate`. Do not edit by hand.",
        "-->",
    ],
)
"""Header of every generated page: licensing plus a warning not to hand-edit."""
# REUSE-IgnoreEnd


def _schema(model: type[BaseModel]) -> str:
    """Return a model's JSON Schema as formatted JSON."""
    return json.dumps(model.model_json_schema(), indent=2, sort_keys=True) + "\n"


def export_schemas(dest: Path) -> tuple[Path, ...]:
    """Write the JSON Schema of every exported model under `dest`.

    Args:
        dest: the `schemas/` directory.

    Returns:
        The files written, sorted.
    """
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "tools").mkdir(exist_ok=True)
    written: list[Path] = []
    models: list[type[BaseModel]] = [
        *ARTIFACT_MODELS,
        Event,
        RunSnapshot,
        ToolCall,
        ControlMessage,
    ]
    for model in models:
        path = dest / f"{model.__name__}.json"
        path.write_text(_schema(model), encoding="utf-8")
        written.append(path)
    for tool, args_model in TOOL_ARGUMENTS.items():
        path = dest / "tools" / f"{tool.value}.json"
        path.write_text(_schema(args_model), encoding="utf-8")
        written.append(path)
    return tuple(sorted(written))


def _type_name(annotation: Any) -> str:  # noqa: ANN401 - annotations are arbitrary objects
    """Render a field annotation compactly."""
    text = str(annotation)
    for prefix in ("typing.", "niharness.domain.", "<class '", "'>"):
        text = text.replace(prefix, "")
    return text.replace("NoneType", "None")


def _field_table(model: type[BaseModel]) -> str:
    """Render a model's fields as a Markdown table."""
    lines = ["| Field | Type | Default | Description |", "|---|---|---|---|"]
    for name, field in model.model_fields.items():
        default = "required" if field.is_required() else f"`{field.default!r}`"
        description = (field.description or "").replace("|", "\\|")
        lines.append(
            f"| `{name}` | `{_type_name(field.annotation)}` | {default} | {description} |"
        )
    return "\n".join(lines)


def render_events_page() -> str:
    """Render `docs/reference/events.md` from the event catalogue."""
    lines = [
        GENERATED_WARNING,
        "",
        "# Event catalogue",
        "",
        "Run state is this stream. Every payload below appears in `events.jsonl`",
        "wrapped in an envelope that carries `seq`, `ts`, `run_id` and `step_id`.",
        "The TUI reads these and computes nothing of its own.",
        "",
        "## Envelope",
        "",
        _field_table(Event),
        "",
        "## Payloads",
        "",
    ]
    for payload in PAYLOAD_TYPES:
        discriminator = payload.model_fields["type"].default
        doc = (payload.__doc__ or "").strip().splitlines()[0]
        lines += [f"### `{discriminator}`", "", doc, "", _field_table(payload), ""]
    return "\n".join(lines)


def render_config_page() -> str:
    """Render `docs/reference/config.md` from the configuration models."""
    sections: list[tuple[str, type[BaseModel]]] = [
        ("harness.toml (root)", HarnessConfig),
        ("[models]", ModelsConfig),
        ("[sandbox]", SandboxConfig),
        ("[vector]", VectorConfig),
        ("[loop]", LoopThresholds),
        ("[compact]", CompactionPolicy),
        ("[tools]", ToolLimits),
    ]
    lines = [
        GENERATED_WARNING,
        "",
        "# Configuration",
        "",
        "Three layers, each overriding the previous one: shipped defaults, the",
        "hardware profile in `profiles/<name>.toml`, then the project's",
        "`harness.toml`. Environment variables prefixed `NIH_` override all three",
        "(`NIH_COMPACT__THRESHOLD=0.6`).",
        "",
    ]
    for title, model in sections:
        lines += [f"## {title}", "", (model.__doc__ or "").strip(), "", _field_table(model), ""]
    lines += ["## Gate matrix", "", "Detected by marker file; commands per tier:", ""]
    lines += ["| Language | Markers | Quick | Full |", "|---|---|---|---|"]
    for language, gate in GATE_MATRIX.items():
        quick = [c.name for c in gate.commands if GateTier.QUICK in c.tiers]
        full = [c.name for c in gate.commands if GateTier.FULL in c.tiers]
        markers = ", ".join(f"`{marker}`" for marker in gate.markers)
        lines.append(
            f"| {language.value} | {markers} "
            f"| {', '.join(quick) or '-'} | {', '.join(full) or '-'} |",
        )
    return "\n".join([*lines, ""])


def _help_text(app: typer.Typer, args: Sequence[str]) -> str:
    """Return the help output of a command, exactly as a user sees it."""
    result = CliRunner().invoke(app, [*args, "--help"])
    return result.output.strip()


def _subcommands(app: typer.Typer) -> tuple[tuple[str, typer.Typer | None], ...]:
    """Return the registered command and group names of `app`, sorted."""
    entries: list[tuple[str, typer.Typer | None]] = []
    for command in app.registered_commands:
        callback = command.callback
        name = command.name or (callback.__name__.replace("_", "-") if callback else "")
        if name:
            entries.append((name, None))
    for group in app.registered_groups:
        instance = group.typer_instance
        name = group.name or ""
        if name and instance is not None:
            entries.append((name, instance))
    return tuple(sorted(entries, key=lambda entry: entry[0]))


def render_cli_page(app: typer.Typer) -> str:
    """Render `docs/reference/cli.md` from the Typer application."""
    lines = [GENERATED_WARNING, "", "# CLI reference", "", "## `nih`", "", "```text"]
    lines += [_help_text(app, []), "```", ""]
    for name, group in _subcommands(app):
        lines += [f"## `nih {name}`", "", "```text", _help_text(app, [name]), "```", ""]
        if group is None:
            continue
        for child, _ in _subcommands(group):
            lines += [
                f"### `nih {name} {child}`",
                "",
                "```text",
                _help_text(app, [name, child]),
                "```",
                "",
            ]
    return "\n".join(lines)


def generate(project_root: Path, app: typer.Typer) -> None:
    """Regenerate schemas and the generated reference pages."""
    schemas = export_schemas(project_root / "schemas")
    reference = project_root / "docs" / "reference"
    reference.mkdir(parents=True, exist_ok=True)
    pages = {
        reference / "events.md": render_events_page(),
        reference / "config.md": render_config_page(),
        reference / "cli.md": render_cli_page(app),
    }
    for path, content in pages.items():
        path.write_text(content, encoding="utf-8")
    typer.secho(f"{len(schemas)} schema(s) written to schemas/", fg=typer.colors.GREEN)
    for path in pages:
        typer.secho(f"{path.relative_to(project_root)}: written", fg=typer.colors.GREEN)
